# Generate all 56 Minor Arcana
MINOR_ARCANA: List[Card] = []

for (suit, rank), (name, archetype, up_kw, up_prophecy, up_love, up_career, up_spiritual, up_advice,
                     rev_kw, rev_prophecy, rev_love, rev_career, rev_spiritual, rev_advice) in MINOR_LORE.items():
    meta = SUIT_METADATA[suit]
    card_id = f"min_{suit.lower()}_{rank.lower()}"
    MINOR_ARCANA.append(Card(
        id=card_id,
        name=name,
        arcana="Minor",
        suit=suit,
        rank=rank,
        numeral=rank,
        element=meta["element"],
        zodiac_planet=f"{suit} - {meta['realm']}",
        essence=archetype,
        sigil=meta["symbol"],
        upright=CardMeaning(
            keywords=up_kw,
            archetype=f"{archetype} [Upright]",
            prophecy=up_prophecy,
            love=up_love,
            career=up_career,
            spiritual=up_spiritual,
            advice=up_advice
        ),
        reversed=CardMeaning(
            keywords=rev_kw,
            archetype=f"{archetype} [Reversed]",
            prophecy=rev_prophecy,
            love=rev_love,
            career=rev_career,
            spiritual=rev_spiritual,
            advice=rev_advice
        )
    ))

ALL_CARDS: List[Card] = MAJOR_ARCANA + MINOR_ARCANA
CARD_LOOKUP: Dict[str, Card] = {c.id: c for c in ALL_CARDS}
